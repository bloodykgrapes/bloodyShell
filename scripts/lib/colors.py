"""Sample wallpaper brightness and manage wallpaper palettes."""

import argparse
import json
import os
from pathlib import Path
import re
import runpy
import shutil
import subprocess
import tempfile

FILES = runpy.run_path(str(Path(__file__).with_name("files.py")))
HEX_COLOR = re.compile(r"#[0-9a-fA-F]{6}\Z")
KITTY_INCLUDE = "bloodyShell-colors.conf"
KITTY_DIRECTIVE = re.compile(rb"(?m)^[ \t]*(?:glob)?include[ \t]+" + re.escape(KITTY_INCLUDE.encode()) + rb"[ \t]*(?:\r?\n|\Z)")
KITTY_COLORS = {
    "background": "surface",
    "foreground": "on_surface",
    "cursor": "primary",
    "cursor_text_color": "surface",
    "selection_background": "primary_container",
    "selection_foreground": "on_primary_container",
    "url_color": "primary",
    "active_border_color": "primary",
    "inactive_border_color": "outline_variant",
    "active_tab_background": "primary_container",
    "active_tab_foreground": "on_primary_container",
    "inactive_tab_background": "surface_container_low",
    "inactive_tab_foreground": "on_surface_variant",
}
KITTY_ROLES = frozenset(KITTY_COLORS.values())
SHELL_FALLBACKS = {
    "surface_dim": "surface",
    "surface_bright": "surface_container_low",
    "surface_container_lowest": "surface",
    "surface_container": "surface_container_low",
    "surface_container_high": "surface_container_low",
    "surface_container_highest": "surface_container_low",
    "outline": "outline_variant",
}
ROLES = KITTY_ROLES | {"source_color"} | set(SHELL_FALLBACKS)


def checked_colors(roles):
    if not all(isinstance(value, str) and HEX_COLOR.fullmatch(value) for value in roles.values()):
        raise ValueError("Invalid palette colors")
    return roles


def normalize_palette(output):
    colors = json.loads(output)["colors"]
    palettes = {}
    for mode in ("light", "dark"):
        roles = dict(colors[mode]) if mode in colors else {
            role: values[mode] for role, values in colors.items()
            if isinstance(values, dict) and mode in values
        }
        missing = sorted((KITTY_ROLES | {"source_color"}) - roles.keys())
        if missing:
            raise ValueError(f"Missing palette colors: {', '.join(missing)}")
        for role, fallback in SHELL_FALLBACKS.items():
            roles.setdefault(role, roles[fallback])
        palettes[mode] = checked_colors({role: roles[role] for role in ROLES})
    return palettes


def generate_palette(executable, wallpaper):
    version = FILES["run"]([executable, "--version"], capture_output=True, text=True, check=True, timeout=3)
    match = re.search(r"\b(\d+)\.", version.stdout)
    flags = []
    if match and int(match[1]) >= 4:
        flags = ["--old-json-output", "--source-color-index", "0"]
    with tempfile.TemporaryDirectory(prefix="bloodyShell-matugen-") as temporary:
        config = Path(temporary) / "config.toml"
        config.write_text("[config]\n[templates]\n")
        command = [executable, "-c", str(config), "--dry-run", "--json", "hex", *flags, "image", wallpaper]
        result = FILES["run"](command, capture_output=True, text=True, check=True, timeout=15)
    return normalize_palette(result.stdout)


def write_kitty_colors(palette):
    config_home = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    directory = Path(os.environ.get("KITTY_CONFIG_DIRECTORY") or config_home / "kitty").expanduser()
    if palette is not None:
        directory.mkdir(parents=True, exist_ok=True)
    if not directory.exists():
        return
    with FILES["directory_lock"](directory):
        main = directory / "kitty.conf"
        generated = directory / KITTY_INCLUDE
        original, mode = FILES["read_file"](main)
        contents = original or b""
        updated = KITTY_DIRECTIVE.sub(b"", contents)
        if palette is not None:
            colors = "# Generated by bloodyShell\n" + "".join(f"{key} {palette[role]}\n" for key, role in KITTY_COLORS.items())
            FILES["atomic_write"](generated, colors.encode())
            newline = b"\r\n" if b"\r\n" in contents else b"\n"
            if updated and not updated.endswith(b"\n"):
                updated += newline
            updated += f"globinclude {KITTY_INCLUDE}".encode() + newline
        if updated != contents:
            FILES["atomic_write"](main.resolve(), updated, mode)
        if palette is None:
            generated.unlink(missing_ok=True)


def wallpaper_palette(wallpaper):
    executable = shutil.which("matugen")
    if not executable:
        return {"error": "matugenMissing"}
    try:
        image = Path(wallpaper).resolve(strict=True)
        if not image.is_file():
            raise ValueError("Wallpaper image does not exist")
        return {"palettes": generate_palette(executable, str(image)), "error": ""}
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError):
        return {"error": "wallpaperFailed"}


def wallpaper_brightness(wallpaper):
    size = 32
    try:
        image = Path(wallpaper).resolve(strict=True)
        if not image.is_file():
            return {"light": False}
        command = ["ffmpeg", "-nostdin", "-v", "error", "-threads", "1", "-filter_threads", "1",
                   "-protocol_whitelist", "file,pipe", "-i", str(image), "-map", "0:v:0",
                   "-vf", f"scale={size}:{size}:flags=area,format=rgba",
                   "-frames:v", "1", "-f", "rawvideo", "pipe:1"]
        pixels = FILES["run"](command, capture_output=True, check=True, timeout=5).stdout
    except (OSError, ValueError, subprocess.SubprocessError):
        return {"light": False}
    if len(pixels) != size * size * 4:
        return {"light": False}

    # Average linear sRGB luminance, weighted by the visible area of each pixel.
    channels = [value / 255 for value in range(256)]
    linear = [value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4 for value in channels]
    opacity = sum(pixels[3::4])
    luminance = sum((0.2126 * linear[r] + 0.7152 * linear[g] + 0.0722 * linear[b]) * a
                    for r, g, b, a in zip(pixels[::4], pixels[1::4], pixels[2::4], pixels[3::4]))
    return {"light": opacity > 0 and luminance / opacity >= 0.35}


def kitty_colors(action, data):
    if action == "apply" and not shutil.which("kitty"):
        return {"error": "kittyMissing"}
    try:
        roles = None
        if action == "apply":
            payload = json.loads(data)
            roles = checked_colors({role: payload[role] for role in KITTY_ROLES})
        write_kitty_colors(roles)
        return {"error": ""}
    except (OSError, RuntimeError, ValueError, KeyError, TypeError):
        return {"error": "kittyFailed"}


def main():
    parser = argparse.ArgumentParser(description="bloodyShell color schemes")
    commands = parser.add_subparsers(dest="command", required=True)
    generate = commands.add_parser("generate")
    generate.add_argument("wallpaper")
    brightness = commands.add_parser("brightness")
    brightness.add_argument("wallpaper")
    kitty = commands.add_parser("kitty")
    kitty.add_argument("action", choices=("apply", "clear"))
    kitty.add_argument("palette", nargs="?")
    args = parser.parse_args()
    if args.command == "generate":
        result = wallpaper_palette(args.wallpaper)
    elif args.command == "brightness":
        result = wallpaper_brightness(args.wallpaper)
    else:
        result = kitty_colors(args.action, args.palette)
    print(json.dumps(result))
    return 0
